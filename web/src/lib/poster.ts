// URL уменьшенной копии постера.
//
// В БД и в API живёт один `poster_url` — крупная копия (600×900, JPEG). Мелкая
// (400×600, WebP — на четверть легче при том же виде) лежит рядом на диске под тем же именем
// с суффиксом `_sm` и своим расширением; отдельного поля под неё нет
// намеренно: это не отдельная сущность, а тот же постер в другом размере, и хранить
// выводимое значение в базе значило бы держать его в актуальном состоянии.
//
// ⚠️ Правило имени продублировано на бэке (`app/application/ports/storage.py`,
// `thumb_url`) — это единственная строка, которую две стороны обязаны знать одинаково.
// Менять суффикс только вместе, с прогоном `./start.sh thumbs --force`.
//
// Инвариант «мелкая копия есть у каждого постера» держит хранилище (пишет пару) и
// разовый догон для старых файлов. Если её всё же не окажется, `<img>` не должен
// показать дыру — поэтому в карточке стоит откат на крупную (см. `PosterCard`).

export function thumbUrl(posterUrl: string): string {
  const dot = posterUrl.lastIndexOf(".");
  const base = dot < 0 ? posterUrl : posterUrl.slice(0, dot);
  return `${base}_sm.webp`;
}
