"""Порт публикации в публичный канал.

Отдельный мелкий порт, а не метод `TelegramNotifier` (ISP) — и не переиспользование
`send_broadcast`, хотя форма сообщения похожа. Причина техническая и жёсткая:

⚠️ **Кнопки Web App в каналах не работают.** `InlineKeyboardButton(web_app=...)`
Telegram принимает ТОЛЬКО в приватных чатах — в канале такой пост просто не отправится.
Поэтому рассылка в личку (`_broadcast_keyboard`, кнопка `web_app`) и пост в канале
(кнопка `url` на `t.me/<bot>?startapp=m_<id>`) — разные механизмы, и склеивать их в один
метод значило бы прятать это различие внутри условия.

Вторая причина — деградация. Рассылка НЕ глушит ошибки Telegram (их разбирает worker:
спит на RetryAfter, снимает заблокировавших), а публикация в канал глушит: канал —
витрина, и его недоступность не имеет права уронить ни `/add`, ни джоб.

Контент-план добавил три вещи: фото С ДИСКА (`photo_path` — карточки и
портреты лежат в `uploads/channel/`, публичный URL им не нужен), `reply_to_message_id`
(разбор квиза — ответом на сам квиз) и callback-кнопки (варианты A–E: нажатие приходит
боту, в каналах это работает). И `publish` теперь возвращает `message_id`: без него не
привязать комментарии и разбор к посту.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

from app.domain.channel.content.render.base import CallbackButton


@dataclass(frozen=True, slots=True)
class ChannelPost:
    """Пост канала: текст (HTML) + опц. фото с диска + опц. кнопки.

    `photo_path` — путь картинки ОТНОСИТЕЛЬНО медиа-корня (корень знает адаптер, домен
    о раскладке файлов не знает); нет пути → пост уйдёт текстом. Отправки картинки ПО
    URL здесь нет намеренно: её качает сам Telegram со своих серверов, а входящий
    трафик с его диапазонов к нам режет хостер (тот же повод, что у
    `BOT_FORCE_POLLING`) — постер молча не доезжал, и пост уходил текстом.

    `button_url` — только обычная ссылка (`t.me/...`), см. предупреждение в докстринге
    модуля: `web_app`-кнопку канал не примет. `choices` — callback-кнопки одним рядом
    (варианты квиза); с `button_url` не сочетаются — у поста либо ссылка, либо варианты.
    """

    text: str
    photo_path: str | None = None
    button_text: str | None = None
    button_url: str | None = None
    choices: tuple[CallbackButton, ...] = ()
    reply_to_message_id: int | None = None


class ChannelPublisher(Protocol):
    async def publish(self, post: ChannelPost) -> int | None:
        """Опубликовать пост. `message_id` — ушёл; `None` — канал не настроен или сбой.

        Исключений НЕ бросает (деградация в адаптере, как у Redis-адаптеров и журнала
        событий): вызывающие — визард `/add` и джобы планировщика, и для всех упавшая
        публикация в канал куда менее важна, чем то, что они делают. Фильм уже в БД,
        отчёт уже посчитан — падать из-за витрины нельзя.

        `None` вместо тишины, чтобы вызывающий мог записать это в лог по-своему
        (например, отличить «канал не настроен» от «фильм залит, но пост не ушёл»).
        """
        ...

    async def remove_buttons(self, message_id: int) -> bool:
        """Снять клавиатуру с поста (закрытие квиза в 21:00). Тоже без исключений."""
        ...

    async def delete(self, message_id: int) -> bool:
        """Удалить пост из канала (предпросмотр, ошибочная публикация). Без исключений."""
        ...
