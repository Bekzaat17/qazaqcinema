"""Порт закрепления фильма дня админом (DIP).

Обычно фильм дня выбирает правило ротации (`domain/catalog/daily`), и это правильно:
никто не должен каждый день заходить и что-то нажимать. Но иногда день особенный —
вышла новинка, праздник, реклама у блогера, — и тогда нужно сказать «сегодня бесплатно
вот этот фильм». Закреп живёт РОВНО до местной полуночи и исчезает сам: это разовый
жест, а не возврат к ручному курированию главной, от которого мы ушли.

Реализация — `infrastructure/cache/daily_pin.py` (Redis, ключ с TTL до полуночи).
**Fail-open:** Redis недоступен → закрепа нет → работает обычная ротация.
"""

from __future__ import annotations

from typing import Protocol


class DailyPin(Protocol):
    async def get(self, day: int) -> int | None:
        """id закреплённого на эти сутки фильма; None — закрепа нет (обычная ротация)."""
        ...

    async def set(self, day: int, movie_id: int, ttl_seconds: int) -> None:
        """Закрепить фильм на сутки `day`. `ttl_seconds` — сколько осталось до полуночи."""
        ...
