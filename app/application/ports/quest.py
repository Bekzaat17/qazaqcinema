from __future__ import annotations

from contextlib import AbstractAsyncContextManager
from datetime import date
from typing import Protocol

from app.domain.errors import AppError
from app.domain.quest.game import Progress, RankEntry, RankingPeriod, Run


class QuestStorageError(AppError):
    """Хранилище игры временно недоступно."""


class QuestRepository(Protocol):
    async def progress(self, user_id: int, day: date) -> Progress: ...
    async def start(self, run: Run) -> Run: ...
    def locked_run(self, run_id: str, user_id: int) -> AbstractAsyncContextManager[Run | None]: ...
    async def save_answer(self, run: Run, week: date) -> None: ...
    async def leaders(
        self, period: RankingPeriod, week: date, limit: int
    ) -> tuple[RankEntry, ...]: ...
    async def rank(self, user_id: int, period: RankingPeriod, week: date) -> RankEntry | None: ...
    def locked_village(self, user_id: int) -> AbstractAsyncContextManager[Progress]: ...
    async def save_village(self, user_id: int, progress: Progress) -> None: ...


class QuestRankingCache(Protocol):
    async def get(self, key: str) -> tuple[RankEntry, ...] | None: ...
    async def set(self, key: str, entries: tuple[RankEntry, ...], ttl: int) -> None: ...


class QuestChannelStore(Protocol):
    async def message_id(self, key: str) -> int | None: ...
    async def reserve(self, key: str) -> bool: ...
    async def delivered(self, key: str, message_id: int) -> None: ...


class QuestChannelPublisher(Protocol):
    @property
    def channel_id(self) -> int: ...
    async def send(self, text: str) -> int | None: ...
    async def update(self, message_id: int, text: str) -> None: ...
