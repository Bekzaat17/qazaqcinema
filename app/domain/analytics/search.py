"""Спрос, высказанный словами: что люди ищут в каталоге и чего в нём не нашли.

Отдельно от `EventKind` намеренно. `user_events` — это ПЯТЬ значимых фактов воронки
(«пришёл / открыл / посмотрел / оплатил / истёк»), и там у события есть ровно одно
свободное поле `meta`. Поисковый запрос — факт другой природы: у него два измерения
(что спросили И сколько нашлось), а нулевой результат — не шаг воронки, а **заявка
на контент**. Складывать его в `meta` пришлось бы вместе со счётчиком найденного,
закодированным в строку, а группировать — по подстроке растущей многоцелевой таблицы.

Зачем вообще: до этого единственным сигналом спроса были просмотры, то есть выбор
ИЗ УЖЕ ЗАЛИТОГО. Он не отвечает на главный вопрос наполнения — «чего у нас нет».
Список запросов с `found = 0`, отсортированный по частоте, и есть очередь на озвучку:
люди прямым текстом называют, за чем пришли и ушли ни с чем.

Здесь только чистые правила (нормализация + VO результата), без БД и Telegram —
проверяется юнит-тестом, как `pick_daily_id` и `compute_expiry`.
"""

from __future__ import annotations

from dataclasses import dataclass

# Совпадает с длиной колонки `search_queries.query`. Обрезаем, а не отбрасываем:
# длинный запрос — всё равно спрос, терять его из-за лимита строки незачем.
MAX_QUERY_LEN = 64
# Тот же порог, что у поиска на фронте (`App.tsx`): по одной букве каталог не ищут,
# и в спрос такое писать нечего.
MIN_QUERY_LEN = 2


def normalize_query(raw: str) -> str:
    """Привести запрос к виду, в котором его можно СЧИТАТЬ. `""` — писать нечего.

    Нормализация нужна ровно для группировки: «Кунг фу», «кунг  фу» и «КУНГ ФУ» —
    один и тот же спрос, и без сведения к одной форме топ запросов рассыпался бы на
    варианты регистра и лишних пробелов, а частота — та единственная величина, ради
    которой список и собирается.

    Регистр гасим `casefold`, а не `lower`: он корректнее для не-ASCII, а у нас
    казахский с ә/ғ/қ/ң/ө/ұ/ү/і.
    """
    collapsed = " ".join(raw.split()).casefold()
    return collapsed[:MAX_QUERY_LEN] if len(collapsed) >= MIN_QUERY_LEN else ""


@dataclass(frozen=True, slots=True)
class SearchDemand:
    """Один запрос в сводке спроса: что искали, сколько раз и сколько разных людей.

    `people` рядом с `hits` обязателен: десять попыток одного человека и десять
    разных людей — это разный по силе сигнал, а в отчёте они выглядели бы одинаково.
    Особенно для нулевых результатов, где один упорный посетитель, перебирающий
    написания одного и того же названия, иначе возглавил бы очередь на озвучку.
    """

    query: str
    hits: int
    people: int
