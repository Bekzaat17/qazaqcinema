"""Проценты для текстов отчётов — общие для дневного и еженедельного.

Не хранятся нигде: это производные величины, а не факты (снимок `daily_reports`
несёт только числители/знаменатели). Формула может поменяться — тексту отчёта
незачем тянуть за собой миграцию.
"""

from __future__ import annotations


def share(part: int, whole: int) -> int | None:
    """Целый процент «part — это N% от whole» (конверсия, доля). Пустой знаменатель

    → `None`, а не деление на ноль и не враньё про «0%» (нечего делить — значит нечего
    и показывать).
    """
    return round(part / whole * 100) if whole else None


def change(current: int, previous: int) -> int | None:
    """Целый процент изменения `current` к `previous` (растёт — плюс, падает — минус).

    `None`, если раньше было 0: относительное изменение от нуля не определено (не
    «+∞%») — в т.ч. покрывает «данных за предыдущий период ещё нет».
    """
    return round((current - previous) / previous * 100) if previous else None
