"""Виды значимых действий пользователя (данные, не полная история).

Пишем НЕ всё подряд, а только то, что меняет состояние или показывает реальный интерес:
первый контакт с ботом, открытие кинотеатра, просмотр, активация и истечение подписки.
Клики по каталогу/карточкам сюда не попадают намеренно — они не отвечают ни на один
вопрос, ради которого заводилась таблица, а объём дали бы на порядок больше.

Значение хранится в БД как VARCHAR (как `UserStatus`/категории): добавить новый вид —
строка здесь, без миграции типа.
"""

from __future__ import annotations

from enum import StrEnum


class EventKind(StrEnum):
    START = "start"          # нажал /start в боте (первый контакт или возврат)
    OPEN = "open"            # открыл Mini App (bootstrap-сессия по initData)
    PLAY = "play"            # получил видео в личку (meta = id фильма)
    SUBSCRIBE = "subscribe"  # подписка активирована/продлена (meta = slug тарифа)
    EXPIRE = "expire"        # подписка истекла (перевод ACTIVE → EXPIRED)
    # Модератор отклонил чек, по которому доступ уже открыли авансом (meta = slug тарифа).
    # Парное к `subscribe`: тот пишется в момент выдачи, ДО проверки чека, и без `revoke`
    # в журнале не отличить оплаченную подписку от аннулированной.
    REVOKE = "revoke"
    # Воронка «сначала ценность, потом оплата»: подарочный первый фильм и упор в пэйволл.
    # Это два ключевых шага конверсии — сколько людей попробовали продукт и сколько из них
    # реально упёрлись в стену. `free_play` пишется вместо `play` (не вдобавок), иначе
    # бесплатные просмотры смешались бы с оплаченными в одной метрике.
    FREE_PLAY = "free_play"  # выдан подарочный фильм (meta = id фильма)
    PAYWALL = "paywall"      # показан пэйволл: доступа нет и подарок уже потрачен
    # Фильм дня: hero главной открыт всем бесплатно ровно сутки.
    # Отдельный вид, а не `free_play`: подарок одноразовый и меряет «попробовал продукт»,
    # а это — регулярный крючок возврата, и смешав их, мы потеряли бы обе метрики.
    DAILY_PLAY = "daily_play"  # посмотрел бесплатный фильм дня (meta = id фильма)
    # Недельный бесплатный выбор (`domain/subscription/weekly`) — три РАЗНЫХ вопроса, и
    # ни один не отвечается чужим счётчиком:
    #   `channel_gate` — сколько людей уткнулись в требование подписки; знаменатель всей
    #     затеи: без него прирост канала не отличить от органического;
    #   `weekly_pick` — сколько ВЗЯЛИ фильм на неделю (ровно один на человека в неделю);
    #   `weekly_play` — сколько раз смотрели, включая пересмотры за ту же неделю.
    # Пишутся оба (`pick` + `play`) на выдаче, где выбор только что забрали: человек и
    # выбрал, и посмотрел. Слей их в один — и «сколько людей попробовали» утонет в
    # пересмотрах, которых теперь семь дней вместо одного раза.
    CHANNEL_GATE = "channel_gate"  # показали «жазылыңыз» (meta = id фильма)
    WEEKLY_PICK = "weekly_pick"    # взял фильм на неделю (meta = id фильма)
    WEEKLY_PLAY = "weekly_play"    # смотрит свой недельный фильм (meta = id фильма)
    # Разрешил боту писать в личку прямо из Mini App (нативный попап Telegram), не уходя
    # в чат за кнопкой START. Отдельный вид, а не `start`: путь другой и конверсию этих
    # двух дорог надо уметь сравнивать. meta = "auto" (initData) либо "prompt" (попап).
    WRITE_ACCESS = "write_access"
    # Последний шаг воронки: человек получил видео и уходит из Mini App в чат смотреть.
    # ⚠️ Уводит его нативный клиент Telegram (`WebApp.close()` / `openTelegramLink`), а эти
    # методы — сообщения по мосту без ответа: сработали они или клиент их проглотил, из кода
    # не видно никак. Единственный способ узнать — считать попытки и те случаи, когда через
    # секунду мы всё ещё на экране. meta = "<исход>:<платформа>" (см. `HandoffOutcome`).
    HANDOFF = "handoff"


class ChannelMemberChange(StrEnum):
    """Движение в публичном канале: подписался или отписался (апдейт `chat_member`).

    Отдельный вид, а не ещё одно значение `EventKind`, по причине из схемы: `user_events`
    ссылается внешним ключом на `users`, а на канал подписываются и те, кто бота ни разу
    не открывал, — такой строке там просто негде лежать. Поэтому своя таблица
    `channel_member_events` и свой enum.

    Зачем вообще считать по головам, если Telegram отдаёт итог одним числом: итог —
    это разность. День, в который пришли 40 и ушли 35, и день, в который не было ни
    одного движения, в отчёте выглядели бы одинаково («+5»), хотя это разные дни и
    разные выводы.
    """

    JOIN = "join"    # вошёл в канал (в т.ч. вернулся после отписки)
    LEAVE = "leave"  # вышел сам либо был удалён/забанен


class HandoffOutcome(StrEnum):
    """Чем кончилась попытка уйти из Mini App в чат за видео."""

    TRY = "try"      # нажал кнопку — мост дёрнут
    STUCK = "stuck"  # секунда прошла, приложение всё ещё на экране: клиент не отреагировал
