"""Виды значимых действий пользователя (данные, не полная история).

Пишем НЕ всё подряд, а только то, что меняет состояние или показывает реальный интерес:
первый контакт с ботом, открытие кинотеатра, просмотр, активация и истечение подписки.
Клики по каталогу/карточкам сюда не попадают намеренно — они не отвечают ни на один
вопрос, ради которого заводилась таблица, а объём дали бы на порядок больше.

Значение хранится в БД как VARCHAR (как `UserStatus`/категории): добавить новый вид —
строка здесь, без миграции типа.
"""

from __future__ import annotations

from enum import StrEnum


class EventKind(StrEnum):
    START = "start"          # нажал /start в боте (первый контакт или возврат)
    OPEN = "open"            # открыл Mini App (bootstrap-сессия по initData)
    PLAY = "play"            # получил видео в личку (meta = id фильма)
    SUBSCRIBE = "subscribe"  # подписка активирована/продлена (meta = slug тарифа)
    EXPIRE = "expire"        # подписка истекла (перевод ACTIVE → EXPIRED)
    # Воронка «сначала ценность, потом оплата»: подарочный первый фильм и упор в пэйволл.
    # Это два ключевых шага конверсии — сколько людей попробовали продукт и сколько из них
    # реально упёрлись в стену. `free_play` пишется вместо `play` (не вдобавок), иначе
    # бесплатные просмотры смешались бы с оплаченными в одной метрике.
    FREE_PLAY = "free_play"  # выдан подарочный фильм (meta = id фильма)
    PAYWALL = "paywall"      # показан пэйволл: доступа нет и подарок уже потрачен
