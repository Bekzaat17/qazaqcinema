"""Нормализация ответа перед сравнением.

Половина людей пишет казахские слова с русской раскладки («кулын» вместо «құлын»), часть —
латиницей 2021 года («qulyn»/«qūlyn»). Человек при этом ПРАВ, и сказать ему «қате» из-за
раскладки — худшее, что может сделать игра про язык. Поэтому обе стороны (ответ человека и
допустимые варианты) сводятся к одной форме: нижний регистр, латиница → кириллица,
специфичные буквы → ближайшие русские (қ→к, ө→о, ұ/ү→у, ә→а, і→и, ң→н, ғ→г, һ→х), без
пунктуации, пробелы схлопнуты. Сравнивать после этого можно буквально.

Заодно і/ы/й → и: в латинице `y` пишут и за «й», и за «ы», а «і»/«ы» на слух путают
часто — для игры это одна буква. Ложных совпадений это почти не даёт: слова, различающиеся
только этими буквами, в ответах-жұмбақ не встречаются.
"""

from __future__ import annotations

import re

# Специфичные буквы казахской кириллицы → «русские соседи» (то, что набирают без раскладки).
_FOLD = str.maketrans(
    {
        "ә": "а", "ғ": "г", "қ": "к", "ң": "н", "ө": "о", "ұ": "у", "ү": "у", "һ": "х",
        "і": "и", "ы": "и", "ё": "е", "й": "и", "ъ": "", "ь": "",
    }
)

# Латиница-2021 (и бытовая транслитерация) → кириллица. Диграфы — раньше одиночных букв.
_LATIN_DIGRAPHS = (
    ("sh", "ш"), ("ch", "ч"), ("zh", "ж"), ("ng", "н"), ("ts", "ц"), ("ya", "я"), ("yu", "ю"),
)
_LATIN = str.maketrans(
    {
        "a": "а", "ä": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г", "ğ": "г",
        "h": "х", "i": "и", "ı": "ы", "j": "ж", "k": "к", "l": "л", "m": "м", "n": "н", "ñ": "н",
        "o": "о", "ö": "о", "p": "п", "q": "к", "r": "р", "s": "с", "ş": "ш", "t": "т",
        "u": "у", "ü": "у", "ū": "у", "v": "в", "w": "у", "x": "х", "y": "и", "z": "з",
    }
)

_NOT_LETTERS = re.compile(r"[^\w\s]|_", re.UNICODE)


def fold(text: str) -> str:
    """Каноническая форма для сравнения. `fold("Қой!") == fold("koi") == fold("кой")`."""
    t = text.strip().lower()
    for digraph, letter in _LATIN_DIGRAPHS:
        t = t.replace(digraph, letter)
    t = t.translate(_LATIN).translate(_FOLD)
    t = _NOT_LETTERS.sub(" ", t)
    return re.sub(r"\s+", " ", t).strip()


def levenshtein(a: str, b: str) -> int:
    """Редакционное расстояние — для допуска опечатки. Строки короткие (слова), O(n·m) хватит."""
    if a == b:
        return 0
    if not a or not b:
        return len(a) + len(b)
    previous = list(range(len(b) + 1))
    for i, ca in enumerate(a, start=1):
        current = [i]
        for j, cb in enumerate(b, start=1):
            current.append(min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + (ca != cb)))
        previous = current
    return previous[-1]
