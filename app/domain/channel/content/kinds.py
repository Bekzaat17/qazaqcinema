"""Виды контента канала = ФОРМЫ поста (данные, хранятся VARCHAR — как `EventKind`).

Именно форма, а не тема: у формы свой рендерер и своя механика (кнопки, комментарии,
разрез на несколько сообщений), у темы — только подпись и хэштег. Смешай их — и на
каждую новую рубрику пришлось бы писать класс, отличающийся одной эмодзи.
"""

from __future__ import annotations

from enum import StrEnum


class ContentKind(StrEnum):
    # Квиз с вариантами A–E — инлайн-кнопки под постом, ответ приходит как callback
    # (в каналах работает, в отличие от web_app-кнопок и опросов). Мақал «жалғастыр»,
    # атау-сұрақ.
    QUIZ_CHOICE = "quiz_choice"
    # Квиз с открытым ответом словом — ответы в комментариях группы обсуждений,
    # проверяются нормализацией + `accept[]`. Жұмбақ.
    QUIZ_OPEN = "quiz_open"
    # Длинный текст (қара сөз): один пост, при длине >4096 режется по абзацам и уходит
    # несколькими сообщениями подряд. НЕ по дням — смысл не должен обрываться.
    LONGREAD = "longread"
    # Цитата + автор (нақыл сөз): короткий текст, обычно с карточкой-картинкой.
    SAYING = "saying"
    # Список «термин → значение» (атаулары: жылқы жасы, туыстық атаулар, киім…).
    TERM_LIST = "term_list"
    # Поздравление с праздником (`domain/channel/holidays.py`): картинка + 2–4 строки
    # тёплого текста. Без inline-кнопки НАМЕРЕННО — пост с кнопками Telegram не
    # пересылает в группу обсуждений, а праздник ровно тот случай, когда люди
    # поздравляют друг друга сами (см. CLAUDE.md, «Публичный канал»).
    GREETING = "greeting"

    @property
    def is_quiz(self) -> bool:
        return self in (ContentKind.QUIZ_CHOICE, ContentKind.QUIZ_OPEN)
