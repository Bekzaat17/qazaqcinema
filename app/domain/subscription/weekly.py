"""Недельное окно бесплатного выбора — чистая математика, без БД и Telegram.

Окно ОБЩЕЕ для всех: понедельник 00:00 по Алматы. Не «7 дней с момента выбора» —
персональный срок означал бы свой счётчик у каждого, колонку со временем и джоб, который
эти сроки гасит. Общее окно не требует ничего из этого: право освобождается сменой ключа
недели, и в БД для этого не пишется ни строки.

Ключ окна — ДАТА понедельника (`2026-09-21`), а не номер ISO-недели: дата читается в логе
и в psql без календаря под рукой, и сразу видно, о какой неделе речь. NULL = человек не
выбирал ни разу; «прошлая неделя» и «ни разу» одинаково означают «свободно», и обе
ситуации ловит одно сравнение.

Зона — тот же `TZ`, что у фильма дня и сетки канала. Границы суток, недели и контент-плана
обязаны совпадать: иначе «жаңа апта» наступит в приложении не тогда, когда о ней напишет
канал, и человек увидит закрытый выбор под постом «выбор открыт».

Цена общего окна названа честно: взявший фильм в воскресенье вечером получит вечер, а не
неделю. Лечится это не кодом, а напоминанием в субботу тем, кто выбор ещё не потратил.
"""

from __future__ import annotations

from datetime import date, datetime, time, timedelta

from app.domain.catalog.daily import TZ


def week_start(now: datetime) -> date:
    """Понедельник текущей МЕСТНОЙ недели — ключ окна выбора."""
    today = now.astimezone(TZ).date()
    return today - timedelta(days=today.weekday())


def week_end(now: datetime) -> datetime:
    """Когда окно закроется: ближайший понедельник 00:00 по Алматы.

    Одна точка отсчёта на всех — фронту незачем считать «қалды» по каждому юзеру, ему
    хватает этого момента.
    """
    return datetime.combine(week_start(now) + timedelta(days=7), time.min, tzinfo=TZ)


# Сколько недель человек считается «ещё живым» для субботнего напоминания. Ограничение
# обязательное, а не вежливое: без него письмо «успейте взять» капало бы каждую субботу
# ВЕЧНО всякому, кто однажды воспользовался выбором и ушёл. Месяц молчания — достаточный
# ответ; дальше человек либо вернётся сам, либо ему это не нужно.
IDLE_REMINDER_WEEKS = 4


def idle_horizon(now: datetime) -> date:
    """Самая ранняя неделя, чей выбор ещё делает человека адресатом напоминания."""
    return week_start(now) - timedelta(weeks=IDLE_REMINDER_WEEKS)
