def faq_for(heading_ru: str, count: int) -> list[FaqItem]:
    """Вопросы-ответы страницы: шаблоны с подставленной темой и числом фильмов.

    Тема идёт в РУССКОЙ формулировке даже в казахском вопросе — именно она совпадает с
    тем, как запрос набирают («мультики для детей на казахском»), и именно её человек
    ожидает увидеть в вопросе про страницу, на которую попал.
    """
    return [
        FaqItem(
            question=item.question.format(ru=heading_ru, count=count),
            answer=item.answer.format(ru=heading_ru, count=count),
        )
        for item in FAQ_TEMPLATES
    ]
