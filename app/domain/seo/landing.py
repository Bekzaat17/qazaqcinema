def landing_for(category: Category) -> CategoryLanding:
    """Тексты страницы категории. Записи нет → осмысленный дефолт из справочника.

    Дефолт здесь, рядом с таблицей: новая категория обязана получить страницу сразу,
    а не ждать, пока кто-нибудь допишет ей тексты.
    """
    known = LANDINGS.get(category.slug)
    if known is not None:
        return known
    return CategoryLanding(
        heading_kk=f"{category.title_kk} қазақша",
        heading_ru=f"{category.title_ru} на казахском языке",
        intro=(
            f"{category.title_kk} — қазақ тілінде онлайн көріңіз. "
            f"{category.title_ru} на казахском языке, смотрите в Telegram."
        ),
    )


