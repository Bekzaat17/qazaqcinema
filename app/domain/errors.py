"""Общее основание для СВОИХ ошибок: `AppError`.

Одно основание нужно границам. Роутер, хендлер и джоб должны уметь отличить «сломалось
наше правило» (заявка уже обработана, тариф неизвестен, YAML битый) от «сломалась
библиотека или сеть» — и поймать первое одной строкой, не перечисляя классы.

Живёт в домене, потому что домен — самый внутренний слой: его импортируют все, он —
никого. Наследники объявляются РЯДОМ с тем портом или сервисом, который их бросает
(`UnknownTariffError` — у платежей, `SeedError` — у сидера): так по имени видно, где
искать причину, а не в общей свалке исключений.

⚠️ Чужие исключения (`TelegramBadRequest`, `SQLAlchemyError`, `OSError`) наружу из
адаптера НЕ выпускаем — адаптер переводит их в исключение своего порта или в
Outcome-значение. Иначе aiogram и sqlalchemy протекают в слои, которые про них не знают.

Ожидаемые ветки (нет доступа, повторный клик, флуд-лимит) — это НЕ ошибки: у них
Outcome-энум (`PlaybackOutcome`, `DeleteOutcome`, `ModerationOutcome`). Исключение —
для того, что сломалось.
"""

