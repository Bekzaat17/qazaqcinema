"""Фильм дня — какой фильм сегодня открыт всем бесплатно. Чистая функция.

Решение 2026-08-19 (заменяет курируемый hero): hero главной И ЕСТЬ фильм дня. Раньше
на первом экране висела просто красивая карточка — человек жал «Көру» и упирался в
пэйволл, то есть лучшее место экрана ничего не обещало. Теперь оно обещает конкретное:
вот это кино сегодня можно посмотреть бесплатно.

Выбор **детерминированный по суткам**, а не `random` на запрос: главная кэшируется и
одна на всех — случайность «на запрос» давала бы разным людям разный фильм дня, а F5
менял бы бесплатное кино под рукой. Один и тот же день всегда даёт один и тот же фильм.

Перестановка на круг (`Random(cycle).shuffle`), а не выбор наугад: внутри круга длиной
в каталог фильмы не повторяются — порядок выглядит случайным, но «два дня подряд одно и
то же» невозможно. Каталог пополнился → длина круга изменилась → порядок пересобрался;
это нормально, единственный инвариант — стабильность ВНУТРИ суток.

Граница суток — **местная полночь (Asia/Almaty)**, а не UTC: «сегодня бесплатно» человек
читает по своим часам, и таймер «қалды» обязан сходиться с его вечером. Контейнеры живут
в UTC, поэтому зона задана явно (та же причина, что у `REPORT_TZ` в scheduler).
"""

from __future__ import annotations

from datetime import datetime, time, timedelta
from random import Random
from zoneinfo import ZoneInfo

TZ = ZoneInfo("Asia/Almaty")


def day_index(now: datetime) -> int:
    """Порядковый номер МЕСТНЫХ суток — ключ выбора и ключ кэша главной."""
    return now.astimezone(TZ).date().toordinal()


def day_start(now: datetime) -> datetime:
    """Начало текущих МЕСТНЫХ суток — граница пула фильма дня.

    В выбор идут только фильмы, добавленные ДО неё. Иначе залитая днём новинка меняла бы
    длину каталога, а с ней — и `divmod`, то есть бесплатное кино подменялось бы прямо
    под руками у зрителя (проверено: +1 фильм к 158 сдвигает выбор с id 77 на id 35).
    Новинка входит в ротацию со следующих суток; нужна сегодня — есть `/daily <id>`.
    """
    return datetime.combine(now.astimezone(TZ).date(), time.min, tzinfo=TZ)


def free_until(now: datetime) -> datetime:
    """Когда фильм дня сменится: ближайшая местная полночь.

    Отдаём наружу (в DTO главной), чтобы обратный отсчёт на фронте не пересчитывал
    часовой пояс сам: правило суток живёт в одном месте — здесь.
    """
    tomorrow = (now.astimezone(TZ) + timedelta(days=1)).date()
    return datetime.combine(tomorrow, time.min, tzinfo=TZ)


def pick_daily_id(ids: list[int], now: datetime) -> int | None:
    """id фильма дня из пула (все фильмы каталога, порядок стабильный). Пусто → None."""
    if not ids:
        return None
    cycle, position = divmod(day_index(now), len(ids))
    order = list(ids)
    Random(cycle).shuffle(order)
    return order[position]
