"""Формула популярности фильма (данные, не логика).

«Танымал» на главной и сорт «по популярности» в каталоге считают ОДИН балл из двух
сигналов, потому что поодиночке каждый врёт:

  • просмотр (`play_count`) — сильный сигнал, но доступен ТОЛЬКО подписчику: у
    непокупателя нет способа его подать, а таких большинство;
  • избранное (`favorites_count`) — слабее (это «хочу посмотреть», а не «посмотрел»),
    зато бесплатно и доступно всем, включая тех, кто ещё не заплатил.

Поэтому просмотр весит больше — иначе избранное, которого физически будет намного
больше, задавило бы просмотры и полка «Танымал» превратилась бы в «список желаний».

Веса — БИЗНЕС-НАСТРОЙКА, менять их здесь (одна строка), не трогая SQL и сервисы.
"""

from __future__ import annotations

PLAY_WEIGHT = 2      # реальный просмотр (оплаченное действие)
FAVORITE_WEIGHT = 1  # звёздочка «в избранное» (бесплатное действие)


def popularity_score(play_count: int, favorites_count: int) -> int:
    """Балл популярности. Чистая функция — та же формула, что в ORDER BY репозитория.

    Держим её здесь, чтобы правило было проверяемо тестом без БД, а SQL лишь повторял
    выражение (`play_count * PLAY_WEIGHT + favorites_count * FAVORITE_WEIGHT`).
    """
    return play_count * PLAY_WEIGHT + favorites_count * FAVORITE_WEIGHT
